/**
 * GIVE THE BUILT WORKER A CLOCK.
 *
 * vinext emits a worker that exports `async scheduled(e,t,n){}` — an empty
 * handler. Cloudflare will happily fire a cron trigger at it and nothing will
 * happen, silently, forever.
 *
 * So after every build this writes a thin entry beside the generated bundle
 * that re-exports it untouched and adds a real scheduled handler.
 *
 * IT HAS TO LIVE INSIDE dist/server. wrangler runs with `no_bundle`, which
 * means it resolves modules relative to the directory holding `main` and
 * uploads whatever matches the ESModule globs. An entry at the repository root
 * makes that directory the repository — so `**\/*.js` starts matching
 * node_modules, and the deploy fails. Keeping the entry next to the bundle
 * keeps the upload exactly what it was before.
 */
import { writeFileSync } from "node:fs";

const ENTRY = new URL("../dist/server/scheduled-entry.mjs", import.meta.url);

writeFileSync(ENTRY, `/* Generated by scripts/add-scheduled-handler.mjs — do not edit. */
import app, { DraftCreationWorkflow, PhotoDeliveryWorkflow } from "./index.js";

export { DraftCreationWorkflow, PhotoDeliveryWorkflow };

/*
  A CONTENT SECURITY POLICY WITH A REAL NONCE.

  The session cookie is readable by page scripts — @supabase/ssr needs its
  browser client to read it — so script execution is the highest-impact
  browser risk here, and a policy with 'unsafe-inline' would be a header that
  looks like a CSP and defends nothing.

  This is the only place every response passes through, and Workers ship
  HTMLRewriter, so the nonce is minted per request and stamped onto every
  script tag as the HTML streams out. That covers Next's own bootstrap
  scripts, which are inline and numerous, without threading a nonce through
  the framework by hand.

  'strict-dynamic' WAS the plan, and report-only is why it is not. Under
  strict-dynamic a host source is ignored entirely, and Next's client-side
  router injects route chunks in a way that does not inherit the trust — the
  walkthrough produced 40 distinct script-src-elem violations, every one of
  them our own /_next/static/chunks. Enforcing that would have broken every
  client-side navigation in the product.

  So: 'self' rather than 'strict-dynamic'. An inline script still needs the
  nonce, which is the whole point — an injected <script> has no nonce and
  does not run, and that is the path from an XSS to the session cookie. What
  'self' additionally permits is loading a .js from our own origin, and this
  app hosts no user-supplied JavaScript, so there is nothing there to load.

  static.cloudflareinsights.com is named explicitly. Cloudflare injects it at
  the edge, AFTER this worker has run, so it can never carry our nonce — it is
  allowlisted by host or it is broken. It is one script, from Cloudflare, on
  Cloudflare, and the alternative is turning Web Analytics off.

  img-src allows https: rather than a list of provider CDNs. Etsy and Printify
  serve listing artwork from hosts that change, and a brittle list would break
  real images to defend against a class — images that cannot execute — where
  the defence buys very little. style-src allows inline: styled-jsx and inline
  style attributes are throughout the app, and unsafe-inline for STYLE does
  not let an attacker run code.

  ENFORCING, as of D1721. It shipped report-only first and that was not a
  formality: the first policy used 'strict-dynamic' and the walkthrough
  produced forty distinct violations, every one a Next route chunk, which
  enforced would have broken client-side navigation on every page. The
  corrected policy was then walked across nine routes and recorded ZERO new
  violations — same total, same newest timestamp, before and after. That is
  what made it safe to enforce.

  report-uri stays. A policy that starts reporting again is telling us
  something changed.
*/
const CSP_REPORT_ONLY = false;

const policy = nonce => [
  "default-src 'self'",
  \`script-src 'nonce-\${nonce}' 'self' https://static.cloudflareinsights.com\`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self' https://*.supabase.co https://static.cloudflareinsights.com",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-src 'none'",
  "worker-src 'self' blob:",
  "report-uri /api/csp-report",
].join("; ");

const mintNonce = () => {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  return btoa(String.fromCharCode(...bytes)).replace(/[+/=]/g, "");
};

export default {
  async fetch(request, env, ctx) {
    const response = await app.fetch(request, env, ctx);
    const type = response.headers.get("content-type") || "";
    if (!type.includes("text/html")) return response;

    const nonce = mintNonce();
    const stamped = new HTMLRewriter()
      .on("script", { element: el => el.setAttribute("nonce", nonce) })
      .transform(response);

    const headers = new Headers(stamped.headers);
    headers.set(
      CSP_REPORT_ONLY
        ? "Content-Security-Policy-Report-Only"
        : "Content-Security-Policy",
      policy(nonce));
    return new Response(stamped.body, {
      status: stamped.status, statusText: stamped.statusText, headers });
  },

  /*
    The sweep is invoked by handing the framework a Request built here in
    memory. It never crosses the network, so Cloudflare never stamps
    cf-connecting-ip on it, and the cron route treats the absence of that
    header as proof the call came from inside the worker. No secret to leak.

    waitUntil rather than await: a cron firing must not be held open for
    however long a slice of Etsy reads takes, and must never throw.
  */
  async scheduled(event, env, ctx) {
    const site = (env.GOLDIE_SITE_URL || "https://thegoldiesuite.com").replace(/\\/$/, "");
    /*
      D1716 · Every job is a POST. These used to be GETs, which meant the work
      sat behind a method that is meant to be safe to repeat and safe to
      follow. The internal-only header check is still what authenticates them;
      the method is now honest about what they do.
    */
    const run = path =>
      ctx.waitUntil(app.fetch(new Request(site + path, { method: "POST" }), env, ctx)
        .catch(() => {}));

    /*
      TWO CLOCKS, AND THEY DO NOT SHARE WORK.

      Cloudflare fires a named event per cron expression. The ten-minute
      schedule runs the listing poller and NOTHING else; the twenty-minute one
      runs everything else and never touches the poller.

      THAT SEPARATION IS LOAD-BEARING, and it was learned the hard way. While
      the twenty-minute firing also started the poller, that seven-minute
      sweep sat at the front of the queue and starved the work behind it: the
      USPTO ingest ran its last file at 06:22 and then stopped dead for nine
      hours with ninety-four files still waiting. Nothing failed loudly. The
      only reason it was caught is that the ingest counters sit in the health
      view, which is the whole argument for putting them there.
    */
    // A dedicated minute tick drains historical trademark files. The route
    // claims one file atomically and retains per-file rate-limit cooldowns.
    if (event.cron === "* * * * *") {
      run("/api/trademark/ingest-tick");
      return;
    }
    if (event.cron === "*/10 * * * *") {
      run("/api/market/poll-tick");
      /*
        CORRELATION RIDES THE FAST CLOCK, BESIDE THE POLLER.

        It is a database join with no Etsy call, so it costs nothing to run
        often and it must keep pace with a sensor that opens roughly 130
        intervals every hundred seconds. On the twenty-minute clock it could
        not: that is the arithmetic that buried the inspector.
      */
      /*
        AND THE SAMPLE IS TAKEN AFTER THE WORK, NOT BESIDE IT.

        These were two separate waitUntil calls on the same firing, so they
        ran concurrently and whichever won the race decided what the gate
        recorded. The backlog reading oscillated — 338, then 0, then 109,
        then 122 — not because work was piling up but because the sampler
        frequently read the queue before the correlator had drained it.

        Measured while diagnosing exactly that: pastEarliest read 122, one
        pass correlated all 122 in 908ms with zero Etsy calls, and
        pastEarliest read 0 immediately after. Coverage across the whole
        segment is 1 and nothing has expired under this architecture, so no
        evidence was ever lost — the instrument was reading its own race.

        A gate failing on an artifact of its own measurement is worse than no
        gate: it teaches the operator that the number does not mean anything.
        The fix is to the instrument. The standard is untouched.

        Persisted rather than watched: a gate that depends on somebody
        remembering to look is not a gate.
      */
      ctx.waitUntil((async () => {
        await app.fetch(new Request(site + "/api/market/correlate", { method: "POST" }), env, ctx)
          .catch(() => {});
        await app.fetch(new Request(site + "/api/market/observe", { method: "POST" }), env, ctx)
          .catch(() => {});
      })());
      /*
        Keep reference images inside Etsy's six-hour display rule. Without this
        they age out and every listing card renders as a blank box — the rule
        working correctly against data nothing was refreshing.
      */
      ctx.waitUntil(
        app.fetch(new Request(site + "/api/design-scanner/recover-images?batches=3",
          { method: "POST" }), env, ctx).catch(() => {}),
      );
      return;
    }

    /*
      SCHEMA FIRST, AND ONLY ON THE SLOW CLOCK.

      Foundational tables used to be created by whichever member happened to
      touch a feature first, which meant their first click carried a
      migration and the capability registry could not tell a broken feature
      from an unused one. This runs every schema owner once; it is idempotent,
      so firing it every twenty minutes is harmless and means a fresh deploy
      is migrated within one cron rather than on first use.
    */
    ctx.waitUntil(
      app.fetch(new Request(site + "/api/operations/migrate", { method: "POST" }), env, ctx)
        .catch(() => {}),
    );

    /* Cheapest and most perishable first, so nothing important queues behind
       a workload that might hang. */
    /* The cheapest question in the system: which shops sold anything. */
    run("/api/market/sensor-tick");
    /* And what the sensor found, inspected while the evidence still exists. */
    run("/api/market/inspect-tick");
    /* One USPTO bulk file. Bounded, and no longer last in the queue. */
    run("/api/trademark/ingest-tick");
    /*
      Shop Watch keeps its evidence inside Etsy's six-hour display rule. The
      member-facing brief is generated once each morning; this only keeps the
      underlying evidence fresh enough to be shown at all.
    */
    ctx.waitUntil(
      app.fetch(new Request(site + "/api/market/shop-watch", { method: "PUT" }), env, ctx)
        .catch(() => {}),
    );
    /*
      The artwork capture queue. A design Goldie fails to keep is one it can
      never prove anything about later, so the work is durable and retried
      rather than attached to whatever request happened to start it.
    */
    run("/api/shop-map/capture-tick");
    /* The corpus sweep, which is what keeps discovery going. */
    run("/api/sold-overnight/cron");
    /*
      AND THE BRIEFS THE MEMBER ACTUALLY READS.

      Reference images were being kept current; the briefs built from them
      were not, because nothing but a member opening a niche ever wrote one.
      Six of seven saved niches were telling her their evidence could not be
      refreshed when nothing had been attempted. Costs no Etsy call.
    */
    run("/api/market/niche-brief-tick");
    /*
      AND THE TWO CLOCKS RECORD THEMSELVES.

      The 72-hour gate and the USPTO backfile both finish on their own
      schedule. Reading them from a health view means the moment either
      finished is only captured if somebody happened to be looking, and a
      desktop reminder that needs an app left open is not automation.

      Last in the queue on purpose: it is two reads and two small writes, it
      must never delay the work it is measuring, and a tick it misses is one
      twenty-minute gap in a history rather than a lost outcome — the outcome
      row is written the first time the condition holds, whenever that is.
    */
    run("/api/operations/evidence-tick");
    /*
      D1717 · Reports of a refused credential arrive from the read paths,
      which never act on them. This is the only place a connection is
      retired, and it asks the provider once more itself before doing it — so
      an outage that produced the refusals cannot cost a member a working
      token.
    */
    run("/api/operations/connection-cleanup-tick");
    /*
      Whole-shop enumeration is NOT on the clock. The estimate killed it as a
      production path — a median of 695 listings per shop and one with 11,202
      and for the modified-order experiment; nothing schedules it.
    */
  },
};
`);

console.log("scheduled entry written to dist/server/scheduled-entry.mjs");
