/**
 * GIVE THE BUILT WORKER A CLOCK.
 *
 * vinext emits a worker that exports `async scheduled(e,t,n){}` — an empty
 * handler. Cloudflare will happily fire a cron trigger at it and nothing will
 * happen, silently, forever.
 *
 * So after every build this writes a thin entry beside the generated bundle
 * that re-exports it untouched and adds a real scheduled handler.
 *
 * IT HAS TO LIVE INSIDE dist/server. wrangler runs with `no_bundle`, which
 * means it resolves modules relative to the directory holding `main` and
 * uploads whatever matches the ESModule globs. An entry at the repository root
 * makes that directory the repository — so `**\/*.js` starts matching
 * node_modules, and the deploy fails. Keeping the entry next to the bundle
 * keeps the upload exactly what it was before.
 */
import { writeFileSync } from "node:fs";

const ENTRY = new URL("../dist/server/scheduled-entry.mjs", import.meta.url);

writeFileSync(ENTRY, `/* Generated by scripts/add-scheduled-handler.mjs — do not edit. */
import app, { DraftCreationWorkflow, PhotoDeliveryWorkflow } from "./index.js";

export { DraftCreationWorkflow, PhotoDeliveryWorkflow };

export default {
  fetch: (request, env, ctx) => app.fetch(request, env, ctx),

  /*
    The sweep is invoked by handing the framework a Request built here in
    memory. It never crosses the network, so Cloudflare never stamps
    cf-connecting-ip on it, and the cron route treats the absence of that
    header as proof the call came from inside the worker. No secret to leak.

    waitUntil rather than await: a cron firing must not be held open for
    however long a slice of Etsy reads takes, and must never throw.
  */
  async scheduled(event, env, ctx) {
    const site = (env.GOLDIE_SITE_URL || "https://thegoldiesuite.com").replace(/\\/$/, "");
    const run = path =>
      ctx.waitUntil(app.fetch(new Request(site + path), env, ctx).catch(() => {}));

    /*
      TWO CLOCKS, AND THEY DO NOT SHARE WORK.

      Cloudflare fires a named event per cron expression. The ten-minute
      schedule runs the listing poller and NOTHING else; the twenty-minute one
      runs everything else and never touches the poller.

      THAT SEPARATION IS LOAD-BEARING, and it was learned the hard way. While
      the twenty-minute firing also started the poller, that seven-minute
      sweep sat at the front of the queue and starved the work behind it: the
      USPTO ingest ran its last file at 06:22 and then stopped dead for nine
      hours with ninety-four files still waiting. Nothing failed loudly. The
      only reason it was caught is that the ingest counters sit in the health
      view, which is the whole argument for putting them there.
    */
    if (event.cron === "*/10 * * * *") {
      run("/api/market/poll-tick");
      /*
        CORRELATION RIDES THE FAST CLOCK, BESIDE THE POLLER.

        It is a database join with no Etsy call, so it costs nothing to run
        often and it must keep pace with a sensor that opens roughly 130
        intervals every hundred seconds. On the twenty-minute clock it could
        not: that is the arithmetic that buried the inspector.
      */
      run("/api/market/correlate");
      /*
        An observation sample every ten minutes, beside the work it measures.
        Persisted rather than watched: a gate that depends on somebody
        remembering to look is not a gate.
      */
      run("/api/market/observe");
      /*
        Keep reference images inside Etsy's six-hour display rule. Without this
        they age out and every listing card renders as a blank box — the rule
        working correctly against data nothing was refreshing.
      */
      ctx.waitUntil(
        app.fetch(new Request(site + "/api/design-scanner/recover-images?batches=3",
          { method: "POST" }), env, ctx).catch(() => {}),
      );
      return;
    }

    /*
      SCHEMA FIRST, AND ONLY ON THE SLOW CLOCK.

      Foundational tables used to be created by whichever member happened to
      touch a feature first, which meant their first click carried a
      migration and the capability registry could not tell a broken feature
      from an unused one. This runs every schema owner once; it is idempotent,
      so firing it every twenty minutes is harmless and means a fresh deploy
      is migrated within one cron rather than on first use.
    */
    ctx.waitUntil(
      app.fetch(new Request(site + "/api/operations/migrate", { method: "POST" }), env, ctx)
        .catch(() => {}),
    );

    /* Cheapest and most perishable first, so nothing important queues behind
       a workload that might hang. */
    /* The cheapest question in the system: which shops sold anything. */
    run("/api/market/sensor-tick");
    /* And what the sensor found, inspected while the evidence still exists. */
    run("/api/market/inspect-tick");
    /* One USPTO bulk file. Bounded, and no longer last in the queue. */
    run("/api/trademark/ingest-tick");
    /*
      Shop Watch keeps its evidence inside Etsy's six-hour display rule. The
      member-facing brief is generated once each morning; this only keeps the
      underlying evidence fresh enough to be shown at all.
    */
    ctx.waitUntil(
      app.fetch(new Request(site + "/api/market/shop-watch", { method: "PUT" }), env, ctx)
        .catch(() => {}),
    );
    /*
      The artwork capture queue. A design Goldie fails to keep is one it can
      never prove anything about later, so the work is durable and retried
      rather than attached to whatever request happened to start it.
    */
    run("/api/shop-map/capture-tick");
    /* The corpus sweep, which is what keeps discovery going. */
    run("/api/sold-overnight/cron");
    /*
      Whole-shop enumeration is NOT on the clock. The estimate killed it as a
      production path — a median of 695 listings per shop and one with 11,202
      and for the modified-order experiment; nothing schedules it.
    */
  },
};
`);

console.log("scheduled entry written to dist/server/scheduled-entry.mjs");
